require "test_helper"

class LedgerVerifierTest < ActiveSupport::TestCase
  setup do
    create_household
    @bill = create_bill(amount: "100.01", shareholder: @ann)
    @account_bill = create_bill(AccountBill, amount: "40.00", payee: "PG&E")
    @payment = ShareholderAccountEntry.create!(
      account: @account, shareholder: @bob, date: Date.new(2024, 3, 20),
      entry_type: "Deposit", entry_amount: "25.01"
    )
  end

  def verify(known_keys: Set.new, account_id: nil)
    LedgerVerifier.new(account_id: account_id, known_keys: known_keys).run
  end

  test "rows generated by the app have no differences" do
    result = verify
    assert_empty result.differences, result.report
    assert_equal 2, result.checked_bills
    assert_equal 1, result.checked_entries
  end

  test "reports a share that drifted from the bill, with both amounts" do
    share = @bill.bill_share_balance_entries.find_by(shareholder: @bob)
    share.update_columns(amount_cents: -2_500)

    difference = verify.unexpected.sole
    assert_equal "share", difference.check
    assert_equal "ShareholderBill##{@bill.id}", difference.record
    assert_equal @bob.id, difference.shareholder_id
    assert_equal(-2_500, difference.stored)
    assert_equal(-2_501, difference.expected)
    assert_match "off by 0.01", difference.to_s
  end

  test "reports missing generated rows" do
    @bill.pot_balance_entry.delete
    @account_bill.balance_event.delete
    @payment.account_offset_balance_entry.delete

    checks = verify.unexpected.map { |d| [ d.check, d.record ] }
    assert_includes checks, [ "pot", "ShareholderBill##{@bill.id}" ]
    assert_includes checks, [ "balance event", "AccountBill##{@account_bill.id}" ]
    assert_includes checks, [ "offset", "ShareholderAccountEntry##{@payment.id}" ]
  end

  test "reports a generated row on the wrong date or account register amount" do
    @bill.balance_event.update_columns(date: Date.new(2024, 3, 16))
    @account_bill.bill_account_entry.update_columns(amount_cents: -3_999)

    checks = verify.unexpected.map(&:check)
    assert_includes checks, "balance event date"
    assert_includes checks, "account entry"
  end

  test "reports duplicate pot entries" do
    PotBalanceEntry.create!(account: @account, bill: @bill, amount_cents: 0, date: @bill.date)

    assert_includes verify.unexpected.map(&:check), "duplicate pot"
  end

  test "allowlisted differences are counted as known, not unexpected" do
    @bill.bill_share_balance_entries.find_by(shareholder: @bob).update_columns(amount_cents: -2_500)
    known = verify.differences.to_set(&:key)

    result = verify(known_keys: known)
    assert_empty result.unexpected
    assert_equal 1, result.known.size
  end

  test "an allowlisted difference is reported again if the stored amount changes" do
    share = @bill.bill_share_balance_entries.find_by(shareholder: @bob)
    share.update_columns(amount_cents: -2_500)
    known = verify.differences.to_set(&:key)
    share.update_columns(amount_cents: -2_400)

    assert_equal 1, verify(known_keys: known).unexpected.size
  end

  test "reads the allowlist file" do
    file = Tempfile.new([ "known", ".yml" ])
    file.write([ { "check" => "share", "record" => "ShareholderBill#1", "shareholder_id" => 4,
                   "stored" => -334, "expected" => -333, "note" => "reviewed" } ].to_yaml)
    file.close

    assert_equal Set[ %w[share ShareholderBill#1 4 -334 -333] ], LedgerVerifier.known_difference_keys(file.path)
  ensure
    file&.unlink
  end

  test "can be limited to one account" do
    @bill.bill_share_balance_entries.find_by(shareholder: @bob).update_columns(amount_cents: -2_500)
    other = Account.create!(name: "Elsewhere")

    assert_empty verify(account_id: other.id).differences
    assert_equal 1, verify(account_id: @account.id).differences.size
  end

  test "JSON output lists unexpected differences" do
    @bill.pot_balance_entry.update_columns(amount_cents: 4)

    json = verify.as_json
    assert_equal 1, json[:unexpected_differences].size
    assert_equal "pot", json[:unexpected_differences].first[:check]
  end

  test "never writes" do
    @bill.bill_share_balance_entries.find_by(shareholder: @bob).update_columns(amount_cents: -2_500)

    assert_no_difference -> { BalanceEntry.sum(:amount_cents) } do
      assert_no_difference -> { PaperTrail::Version.count } do
        verify
      end
    end
  end
end
